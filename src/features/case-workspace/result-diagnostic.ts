import type { CaseRecord, Lang } from '../../../shared/types';
import { currentEvidence } from '../../../shared/current-evidence';

/** Presentation of observed execution outcomes; never infers absence of gambling from failure. */
export function resultDiagnostic(c: CaseRecord, lang: Lang) {
  const t = (ru: string, kk: string) => (lang === 'ru' ? ru : kk);
  const result = (title: string, explanation: string, next: string) => ({
    title,
    explanation,
    next,
  });
  if (['queued', 'collecting', 'analyzing'].includes(c.status))
    return result(
      t('Проверка выполняется', 'Тексеру орындалуда'),
      c.step[lang],
      t(
        'Дождитесь завершения проверки. Результат появится автоматически.',
        'Тексерудің аяқталуын күтіңіз. Нәтиже автоматты түрде көрсетіледі.',
      ),
    );
  const attempts = c.collection?.attempts || [];
  const collected = c.collection?.status === 'adequate';
  const hasConclusion = c.inspection?.stages.some(
    (s) => ['context', 'verification', 'pro_review'].includes(s.id) && s.status === 'completed',
  );
  if (collected && hasConclusion) return undefined;
  if (
    !collected &&
    (c.status === 'failed' || (c.collection && c.collection.status !== 'adequate'))
  ) {
    const codes = attempts.map((a) => a.errorCode || '');
    const has = (pattern: RegExp) => codes.some((code) => pattern.test(code));
    const text = currentEvidence(c)
      .filter((e) => e.kind === 'text')
      .map((e) => e.text || '')
      .join('\n');
    const retry = t(
      'Проверьте введённый адрес. При необходимости исправьте его и запустите новый анализ.',
      'Енгізілген мекенжайды тексеріңіз. Қажет болса, түзетіп, жаңа талдауды бастаңыз.',
    );
    if (
      has(/CAPTCHA|CHALLENGE/) ||
      /verify (that )?you are human|проверяет, что вы не бот|выполнение проверки безопасности|just a moment/i.test(
        text,
      )
    )
      return result(
        t('Защита сайта не пройдена', 'Сайт қорғанысы өтілмеді'),
        t(
          'Получена страница CAPTCHA или проверки браузера. Содержимое сайта за ней не проверено.',
          'CAPTCHA немесе браузерді тексеру беті алынды. Оның артындағы сайт мазмұны тексерілмеді.',
        ),
        t(
          'Повторите проверку с расширенными способами доступа в Pro. Этот результат не означает отсутствия игорных признаков.',
          'Pro режимінде кеңейтілген қол жеткізу тәсілдерімен қайта тексеріңіз. Бұл нәтиже ойын белгілерінің жоқтығын білдірмейді.',
        ),
      );
    if (has(/ENOTFOUND|EAI_NONAME|ERR_NAME_NOT_RESOLVED/))
      return result(
        t('Адрес сайта не найден в DNS', 'Сайт мекенжайы DNS жүйесінде табылмады'),
        t(
          'Не удалось определить IP-адрес введённого домена. Страница не получена и анализ содержимого не выполнен.',
          'Енгізілген доменнің IP мекенжайын анықтау мүмкін болмады. Бет алынбады, мазмұны талданбады.',
        ),
        retry,
      );
    if (has(/ECONNREFUSED|ERR_CONNECTION_REFUSED/))
      return result(
        t('Сайт отклонил соединение', 'Сайт қосылымды қабылдамады'),
        t(
          'При обращении по указанному адресу получен отказ в соединении. Это сетевая ошибка; содержимое сайта не получено.',
          'Көрсетілген мекенжай қосылымды қабылдамады. Бұл желілік қате; сайт мазмұны алынбады.',
        ),
        retry,
      );
    if (has(/CERT|TLS|SSL/))
      return result(
        t('Не удалось установить защищённое соединение', 'Қауіпсіз қосылым орнатылмады'),
        t(
          'Проверка HTTPS-соединения завершилась ошибкой сертификата или TLS. Содержимое сайта не проверено.',
          'HTTPS қосылымын тексеру сертификат немесе TLS қатесімен аяқталды. Сайт мазмұны тексерілмеді.',
        ),
        retry,
      );
    if (has(/TIMEOUT|DEADLINE|ETIMEDOUT|EAI_AGAIN/))
      return result(
        t('Истекло время загрузки сайта', 'Сайтты жүктеу уақыты аяқталды'),
        t(
          'За время попыток не удалось получить достаточно содержимого для анализа.',
          'Әрекеттер уақытында талдау үшін жеткілікті мазмұн алынбады.',
        ),
        t(
          'Повторите проверку позже. Сохранённые попытки доступны в деталях.',
          'Кейін қайта тексеріңіз. Сақталған әрекеттер мәліметтерде қолжетімді.',
        ),
      );
    if (has(/AUTH|LOGIN/) || c.redirects.some((r) => r.status === 401))
      return result(
        t('Для просмотра требуется авторизация', 'Көру үшін авторизация қажет'),
        t(
          'Публичного содержимого недостаточно; закрытые разделы не проверены.',
          'Ашық мазмұн жеткіліксіз; жабық бөлімдер тексерілмеді.',
        ),
        t(
          'Выберите разрешённый сценарий проверки после авторизации в Pro.',
          'Pro режимінде авторизациядан кейінгі рұқсат етілген тексеру сценарийін таңдаңыз.',
        ),
      );
    const status = c.redirects.find((r) => r.status >= 400)?.status;
    if (status)
      return result(
        t(`Сайт вернул ошибку HTTP ${status}`, `Сайт HTTP ${status} қатесін қайтарды`),
        t(
          'Вместо проверяемой страницы получен ответ с ошибкой. Содержание страницы не установлено.',
          'Тексерілетін беттің орнына қате жауабы алынды. Бет мазмұны анықталмады.',
        ),
        retry,
      );
    if (has(/ERR_EMPTY_RESPONSE|ECONNRESET|ERR_CONNECTION_RESET/))
      return result(
        t('Соединение закрыто без содержимого страницы', 'Қосылым бет мазмұнынсыз жабылды'),
        t(
          'Попытки подключения завершились разрывом или пустым сетевым ответом. Причина на стороне сайта или сети не установлена.',
          'Қосылу әрекеттері үзіліспен немесе бос желілік жауаппен аяқталды. Сайттағы не желідегі себеп анықталмады.',
        ),
        retry,
      );
    return result(
      t('Содержимое сайта не получено', 'Сайт мазмұны алынбады'),
      t(
        'Способы сбора не дали читаемую страницу. По сохранённым данным нельзя точнее установить причину.',
        'Жинау тәсілдері оқылатын бетті бермеді. Сақталған деректер себепті нақтылауға жеткіліксіз.',
      ),
      retry,
    );
  }
  if (c.status === 'failed' || c.inspection?.stages.some((s) => s.status === 'failed'))
    return result(
      t('Анализ не завершён', 'Талдау аяқталмады'),
      t(
        'Материалы сохранены, но один или несколько этапов анализа завершились ошибкой. Итоговая оценка не сформирована.',
        'Материалдар сақталды, бірақ талдаудың бір немесе бірнеше кезеңі қатемен аяқталды. Қорытынды баға жасалмады.',
      ),
      t(
        'Откройте детали этапов и повторите анализ сохранённых материалов.',
        'Кезең мәліметтерін ашып, сақталған материалдарды қайта талдаңыз.',
      ),
    );
  return undefined;
}
