import type { CaseRecord, Lang } from '../../../shared/types';
export function AuthenticationSummary({ c, lang }: { c: CaseRecord; lang: Lang }) {
  const a = c.authentication;
  if (!a) return null;
  const t = (ru: string, kk: string) => (lang === 'ru' ? ru : kk);
  return (
    <section className="panel">
      <h3>{t('Доступ после авторизации', 'Авторизациядан кейінгі қолжетімділік')}</h3>
      <p>
        {a.status === 'authenticated'
          ? t(
              'Вход подтверждён. Внутренние страницы сохранены отдельно от публичных.',
              'Кіру расталды. Ішкі беттер ашық беттерден бөлек сақталды.',
            )
          : a.status === 'action_required'
            ? t(
                'Нужно участие пользователя: подтверждение почты, 2FA, CAPTCHA или проверка результата регистрации. Повторная регистрация автоматически не выполняется.',
                'Пайдаланушының қатысуы қажет: пошта, 2FA, CAPTCHA немесе тіркелу нәтижесін тексеру. Қайта тіркелу автоматты орындалмайды.',
              )
            : t(
                'Вход не подтверждён. Выводы по закрытым разделам не сформированы.',
                'Кіру расталмады. Жабық бөлімдер бойынша қорытынды жасалмады.',
              )}
      </p>
      <p>
        {t('Сохранено материалов: ', 'Сақталған материалдар: ')}
        {a.evidenceIds.length} · {Math.round(a.durationMs / 1000)} {t('с', 'с')}
      </p>
    </section>
  );
}
